using System.Data;
using AegisCore.Application.Finance;
using AegisCore.Domain;
using AegisCore.Domain.Entities;
using Microsoft.EntityFrameworkCore;

namespace AegisCore.Infrastructure.Finance;

public sealed class FinanceTreasuryService(AegisDbContext db, IFinanceModuleService finance)
{
    public async Task<CashForecastReport> ForecastAsync(Guid tenantId, DateTime asOf, CancellationToken ct)
    {
        var date = asOf.ToUniversalTime();
        var issued = await db.FeeDemands.AsNoTracking().Where(x => x.TenantId == tenantId && x.IssuedAt >= date.AddDays(-365) && x.IssuedAt <= date).SumAsync(x => (decimal?)x.TotalAmount, ct) ?? 0m;
        var collected = await db.FinancePayments.AsNoTracking().Where(x => x.TenantId == tenantId && x.Status == "SETTLED" && x.SettledAt >= date.AddDays(-365) && x.SettledAt <= date).SumAsync(x => (decimal?)x.Amount, ct) ?? 0m;
        var rate = issued == 0m ? 0m : Math.Min(1m, collected / issued);
        var opening = (await finance.GetCashPositionAsync(tenantId, date, ct)).TotalBalance;
        var committed = await db.FinanceVouchers.AsNoTracking().Where(x => x.TenantId == tenantId && x.VoucherType == "PV" && x.Status == FinanceStates.Approved).SumAsync(x => (decimal?)x.TotalAmount, ct) ?? 0m;
        var buckets = new List<CashForecastBucket>(3);
        var priorThrough = date;
        var projected = opening;
        foreach (var days in new[] { 30, 60, 90 })
        {
            var through = date.AddDays(days);
            var gross = await db.FeeDemands.AsNoTracking().Where(x => x.TenantId == tenantId && x.Status != "PAID" && x.DueDate > priorThrough && x.DueDate <= through).SumAsync(x => (decimal?)x.OutstandingAmount, ct) ?? 0m;
            var inflow = Math.Round(gross * rate, 4, MidpointRounding.ToEven);
            var outflow = days == 30 ? committed : 0m;
            projected += inflow - outflow;
            buckets.Add(new CashForecastBucket(through, opening, inflow, outflow, projected));
            opening = projected;
            priorThrough = through;
        }
        return new CashForecastReport(date, Math.Round(rate * 100m, 4, MidpointRounding.ToEven), buckets);
    }

    public async Task<FinanceBankFeedTransaction> PostReconciliationAdjustmentAsync(Guid tenantId, Guid actorId, Guid feedId, PostBankReconciliationAdjustmentCommand command, CancellationToken ct)
    {
        return await db.Database.CreateExecutionStrategy().ExecuteAsync(async () =>
        {
            if (tenantId == Guid.Empty || actorId == Guid.Empty || command.OffsetAccountId == Guid.Empty || string.IsNullOrWhiteSpace(command.Description) || command.Description.Length > 500)
                throw new ArgumentException("Bank adjustment fields are invalid.");
            await using var transaction = await db.Database.BeginTransactionAsync(IsolationLevel.Serializable, ct);
            var feed = await db.FinanceBankFeedTransactions.Include(x => x.BankAccount).SingleOrDefaultAsync(x => x.TenantId == tenantId && x.Id == feedId, ct)
                ?? throw new KeyNotFoundException("Bank feed transaction was not found.");
            if (feed.Status != "UNMATCHED") throw new InvalidOperationException("Only unmatched bank feed transactions may be posted.");
            if (!await db.ChartOfAccounts.AnyAsync(x => x.TenantId == tenantId && x.Id == command.OffsetAccountId, ct)) throw new KeyNotFoundException("Offset account was not found.");
            var amount = Math.Abs(feed.Amount);
            if (amount == 0m) throw new InvalidOperationException("A zero bank movement cannot be posted.");
            var bankDebit = feed.Amount > 0m ? amount : 0m;
            var bankCredit = feed.Amount < 0m ? amount : 0m;
            var entry = new JournalEntry
            {
                Id = Guid.NewGuid(), TenantId = tenantId, EntryNumber = $"BANK-ADJ-{feed.Id:N}"[..40], EntryType = JournalEntryType.AutoGenerated,
                Description = command.Description.Trim(), EntryDate = feed.BookingDate, TotalDebit = amount, TotalCredit = amount,
                IsPosted = true, PostedByUserId = actorId, PostedAt = DateTime.UtcNow,
                Lines =
                [
                    new JournalEntryLine { Id = Guid.NewGuid(), TenantId = tenantId, ChartOfAccountId = feed.BankAccount.ChartOfAccountId, Debit = bankDebit, Credit = bankCredit },
                    new JournalEntryLine { Id = Guid.NewGuid(), TenantId = tenantId, ChartOfAccountId = command.OffsetAccountId, Debit = bankCredit, Credit = bankDebit }
                ]
            };
            db.JournalEntries.Add(entry);
            feed.Status = "POSTED";
            feed.MatchedJournalEntryId = entry.Id;
            await db.SaveChangesAsync(ct);
            await transaction.CommitAsync(ct);
            return feed;
        });
    }

    public async Task<FinanceInvestmentBenchmark> RecordBenchmarkAsync(Guid tenantId, RecordInvestmentBenchmarkCommand command, CancellationToken ct)
    {
        var name = Required(command.Name, 80, "Benchmark name");
        var source = Required(command.Source, 100, "Benchmark source");
        if (tenantId == Guid.Empty || command.ObservationDate == default || command.AnnualReturnPercent is < -100m or > 1000m) throw new ArgumentException("Benchmark fields are invalid.");
        var row = await db.FinanceInvestmentBenchmarks.SingleOrDefaultAsync(x => x.TenantId == tenantId && x.Name == name && x.ObservationDate == command.ObservationDate, ct);
        if (row is null)
        {
            row = new FinanceInvestmentBenchmark { Id = Guid.NewGuid(), TenantId = tenantId, Name = name, ObservationDate = command.ObservationDate, AnnualReturnPercent = command.AnnualReturnPercent, Source = source };
            db.FinanceInvestmentBenchmarks.Add(row);
        }
        else
        {
            row.AnnualReturnPercent = command.AnnualReturnPercent;
            row.Source = source;
        }
        await db.SaveChangesAsync(ct);
        return row;
    }

    public async Task<IReadOnlyList<InvestmentMaturityBucket>> MaturityLadderAsync(Guid tenantId, DateTime from, DateTime to, CancellationToken ct)
    {
        if (to <= from) throw new ArgumentException("Maturity range is invalid.");
        var rows = await db.FinanceInvestmentHoldings.AsNoTracking().Where(x => x.TenantId == tenantId && x.Status == "HELD" && x.MaturityDate >= from && x.MaturityDate <= to)
            .Select(x => new { Date = x.MaturityDate!.Value, x.MarketValue }).ToListAsync(ct);
        return rows.GroupBy(x => x.Date.ToString("yyyy-MM", System.Globalization.CultureInfo.InvariantCulture))
            .OrderBy(x => x.Key).Select(x => new InvestmentMaturityBucket(x.Key, x.Sum(y => y.MarketValue), x.Count())).ToArray();
    }

    public async Task<object> PerformanceAgainstBenchmarksAsync(Guid tenantId, CancellationToken ct)
    {
        var holdings = await db.FinanceInvestmentHoldings.AsNoTracking().Where(x => x.TenantId == tenantId && x.Status == "HELD").ToListAsync(ct);
        var weightedYield = holdings.Sum(x => x.MarketValue) == 0m ? 0m : holdings.Sum(x => x.MarketValue * x.AnnualYieldPercent) / holdings.Sum(x => x.MarketValue);
        var observations = await db.FinanceInvestmentBenchmarks.AsNoTracking().Where(x => x.TenantId == tenantId).GroupBy(x => x.Name).Select(x => x.OrderByDescending(y => y.ObservationDate).First()).ToListAsync(ct);
        return new { portfolioAnnualYieldPercent = Math.Round(weightedYield, 4, MidpointRounding.ToEven), benchmarks = observations.Select(x => new { x.Name, x.ObservationDate, x.AnnualReturnPercent, variancePercent = Math.Round(weightedYield - x.AnnualReturnPercent, 4, MidpointRounding.ToEven) }) };
    }

    private static string Required(string value, int maxLength, string field)
    {
        var result = value?.Trim() ?? string.Empty;
        if (result.Length is 0 || result.Length > maxLength) throw new ArgumentException($"{field} is invalid.");
        return result;
    }
}
